#include <iostream>
#include <iomanip> // Для выравнивания вывода (setw)
#include<windows.h>

using namespace std;

int main() {
    SetConsoleCP(1251);
    SetConsoleOutputCP(1251);

    // ==========================================
    // ЗАДАЧА А: Прямоугольный треугольник из '*'
    // ==========================================
    cout << "--- Задача А ---" << endl;
    int n;
    cout << "Введите высоту треугольника (n): ";
    cin >> n;

    // Внешний цикл отвечает за строки
    for (int i = 1; i <= n; ++i) {
        // Внутренний цикл отвечает за вывод звездочек в текущей строке
        // Количество звездочек равно номеру строки (i)
        for (int j = 1; j <= i; ++j) {
            cout << "*";
        }
        cout << endl; // Переход на новую строку
    }

    cout << endl; // Отступ между задачами

    // ==========================================
    // ЗАДАЧА Б: Трехзначные числа, сумма цифр которых равна k
    // ==========================================
    cout << "--- Задача Б ---" << endl;
    int k;
    cout << "Введите число k: ";
    cin >> k;

    cout << "Найденные числа:" << endl;

    // Перебираем все трехзначные числа от 100 до 999
    for (int num = 100; num <= 999; ++num) {
        // Находим цифры числа
        // num / 100 - сотни
        // (num / 10) % 10 - десятки
        // num % 10 - единицы
        int hundreds = num / 100;
        int tens = (num / 10) % 10;
        int units = num % 10;

        // Проверяем условие: сумма цифр равна k
        if (hundreds + tens + units == k) {
            // Выводим число, выравнивая по ширине (например, 5 символов)
            cout << setw(5) << num;
        }
    }
    cout << endl;

    return 0;
}