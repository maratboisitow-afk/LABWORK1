#include <iostream>
#include<windows.h>
using namespace std;

int main() {
    SetConsoleCP(1251);
    SetConsoleOutputCP(1251);

    long long n;
    cout << "Введите число: ";
    cin >> n;

    long long temp = n;
    int sum = 0;

    // Если число отрицательное, берем модуль для корректной работы с цифрами
    if (temp < 0) temp = -temp;

    while (temp > 0) {
        sum += temp % 10; // Добавляем последнюю цифру
        temp /= 10;       // Убираем последнюю цифру
    }

    cout << "Сумма цифр числа " << n << " равна: " << sum << endl;
    return 0;
}

