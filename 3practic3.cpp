#include <iostream>
#include <climits> // Для INT_MAX и INT_MIN
#include <windows.h>
using namespace std;

int main() {
    SetConsoleCP(1251);
    SetConsoleOutputCP(1251);

    int num;
    int maxVal = INT_MIN;
    int minVal = INT_MAX;
    bool first = true;

    cout << "Вводите числа (0 для завершения):" << endl;
    while (cin >> num && num != 0) {
        if (first) {
            maxVal = minVal = num;
            first = false;
        }
        else {
            if (num > maxVal) maxVal = num;
            if (num < minVal) minVal = num;
        }
    }

    if (!first) {
        cout << "Максимум: " << maxVal << endl;
        cout << "Минимум: " << minVal << endl;
    }
    else {
        cout << "Числа не были введены." << endl;
    }
    return 0;
}
